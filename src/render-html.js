/**
 * Vertical bars for a long-ish series (months).
 * @param {number[]} values
 * @param {string[]} keys
 * @param {{ height?: number }} [options]
 */
function columnChartSvg(values, keys, options = {}) {
  const height = options.height ?? 200;
  const width = 1000;
  const pad = { top: 14, right: 14, bottom: 26, left: 44 };
  const innerW = width - pad.left - pad.right;
  const innerH = height - pad.top - pad.bottom;
  const max = Math.max(...values, 1);
  const slot = innerW / Math.max(1, values.length);
  const barWidth = Math.max(1.5, slot * 0.68);
  const maxLabel = Math.max(1, Math.round(values.length / 10));

  let bars = '';
  values.forEach((value, index) => {
    const barHeight = (value / max) * innerH;
    const x = pad.left + index * slot + (slot - barWidth) / 2;
    const y = pad.top + innerH - barHeight;
    bars += `<rect class="col" x="${x.toFixed(2)}" y="${y.toFixed(2)}" width="${barWidth.toFixed(2)}" height="${Math.max(0.6, barHeight).toFixed(2)}" rx="${Math.min(3, barWidth / 2).toFixed(2)}"><title>${escapeHtml(`${prettyMonth(keys[index])} — ${num(value)} commits`)}</title></rect>`;
  });

  const gridLines = [0, 0.5, 1].map((ratio) => {
    const y = pad.top + innerH - ratio * innerH;
    return `<line class="grid" x1="${pad.left}" y1="${y}" x2="${width - pad.right}" y2="${y}"/>
      <text class="axis" x="${pad.left - 8}" y="${y + 4}" text-anchor="end">${compact(max * ratio)}</text>`;
  }).join('');

  const xTicks = keys
    .map((key, index) => (index % maxLabel === 0 || index === keys.length - 1
      ? `<text class="axis" x="${(pad.left + index * slot + slot / 2).toFixed(1)}" y="${height - 6}" text-anchor="middle">${escapeHtml(key.slice(0, 4))}</text>`
      : ''))
    .join('');

  return `<div class="chart-scroll">${svgBox(width, height, `${gridLines}${bars}${xTicks}`)}</div>`;
}

