/**
 * @param {Array<{ label: string, value: number, color: string }>} segments
 * @param {{ size?: number }} [options]
 */
function donutSvg(segments, options = {}) {
  const size = options.size ?? 200;
  const radius = size / 2 - 10;
  const stroke = 22;
  const circumference = 2 * Math.PI * radius;
  const total = segments.reduce((acc, segment) => acc + segment.value, 0) || 1;

  let offset = 0;
  let rings = '';
  for (const [index, segment] of segments.entries()) {
    const share = segment.value / total;
    const length = share * circumference;
    rings += `<circle cx="${size / 2}" cy="${size / 2}" r="${radius}" fill="none"
      stroke="${escapeHtml(segment.color)}" stroke-width="${stroke}"
      stroke-dasharray="${length.toFixed(2)} ${(circumference - length).toFixed(2)}"
      stroke-dashoffset="${(-offset).toFixed(2)}" stroke-linecap="butt"
      transform="rotate(-90 ${size / 2} ${size / 2})" class="donut-seg">
      <title>${escapeHtml(`${segment.label} — ${num(segment.value)} bytes (${(share * 100).toFixed(1)}%)`)}</title>
    </circle>`;
    offset += length;
    if (index > 40) break;
  }

  const top = segments[0];
  return `<svg class="donut" viewBox="0 0 ${size} ${size}" width="${size}" height="${size}" role="img" aria-label="Language distribution">
    ${rings}
    <text x="${size / 2}" y="${size / 2 - 2}" text-anchor="middle" class="donut-value">${escapeHtml(percent(top?.value ?? 0, total).toFixed(0))}%</text>
    <text x="${size / 2}" y="${size / 2 + 18}" text-anchor="middle" class="donut-label">${escapeHtml(truncate(top?.label ?? '', 14))}</text>
  </svg>`;
}

