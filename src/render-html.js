/* ------------------------------------------------------------- svg: punchcard */

const WEEKDAY_NAMES = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
const WEEKDAY_SHORT = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

/**
 * @param {number[][]} matrix 7 x 24
 */
function punchcardSvg(matrix) {
  const cell = 22;
  const gap = 3;
  const padLeft = 44;
  const padTop = 24;
  const width = padLeft + 24 * (cell + gap) + 12;
  const height = padTop + 7 * (cell + gap) + 18;
  const max = Math.max(1, ...matrix.flat());

  let rects = '';
  for (let day = 0; day < 7; day += 1) {
    for (let hour = 0; hour < 24; hour += 1) {
      const value = matrix[day][hour];
      const x = padLeft + hour * (cell + gap);
      const y = padTop + day * (cell + gap);
      const alpha = value === 0 ? 0.05 : 0.16 + 0.84 * Math.sqrt(value / max);
      rects += `<rect x="${x}" y="${y}" width="${cell}" height="${cell}" rx="5" fill="url(#punch)" opacity="${alpha.toFixed(3)}"><title>${escapeHtml(`${WEEKDAY_NAMES[day]} ${String(hour).padStart(2, '0')}:00 — ${value} commits`)}</title></rect>`;
    }
  }

  const hourLabels = [0, 3, 6, 9, 12, 15, 18, 21]
    .map((hour) => `<text x="${padLeft + hour * (cell + gap) + cell / 2}" y="${height - 4}" text-anchor="middle">${String(hour).padStart(2, '0')}</text>`)
    .join('');
  const dayLabels = WEEKDAY_SHORT
    .map((name, day) => `<text x="${padLeft - 10}" y="${padTop + day * (cell + gap) + cell / 2 + 4}" text-anchor="end">${name}</text>`)
    .join('');

  return `<div class="chart-scroll">${svgBox(width, height, `
    <defs>
      <linearGradient id="punch" x1="0" y1="0" x2="1" y2="1">
        <stop offset="0%" stop-color="#7c5cff"/><stop offset="100%" stop-color="#22d3ee"/>
      </linearGradient>
    </defs>
    ${rects}${hourLabels}${dayLabels}
  `)}</div>`;
}

