/**
 * Area + line chart for a cumulative series.
 * @param {number[]} values
 * @param {string[]} keys
 * @param {{ height?: number }} [options]
 */
function areaChartSvg(values, keys, options = {}) {
  const height = options.height ?? 220;
  const width = 1000;
  const pad = { top: 16, right: 16, bottom: 26, left: 54 };
  const innerW = width - pad.left - pad.right;
  const innerH = height - pad.top - pad.bottom;
  const max = Math.max(...values, 1);
  const step = values.length > 1 ? innerW / (values.length - 1) : 0;

  const points = values.map((value, index) => {
    const x = pad.left + index * step;
    const y = pad.top + innerH - (value / max) * innerH;
    return { x, y, value, key: keys[index] };
  });

  const line = points.map((point, index) => `${index === 0 ? 'M' : 'L'}${point.x.toFixed(1)},${point.y.toFixed(1)}`).join(' ');
  const area = `${line} L${points[points.length - 1].x.toFixed(1)},${pad.top + innerH} L${points[0].x.toFixed(1)},${pad.top + innerH} Z`;

  const gridLines = [0, 0.25, 0.5, 0.75, 1].map((ratio) => {
    const y = pad.top + innerH - ratio * innerH;
    return `<line class="grid" x1="${pad.left}" y1="${y}" x2="${width - pad.right}" y2="${y}"/>
      <text class="axis" x="${pad.left - 8}" y="${y + 4}" text-anchor="end">${compact(max * ratio)}</text>`;
  }).join('');

  const xTicks = [0, 0.25, 0.5, 0.75, 1].map((ratio) => {
    const index = Math.min(points.length - 1, Math.round(ratio * (points.length - 1)));
    const point = points[index];
    if (!point) return '';
    return `<text class="axis" x="${point.x}" y="${height - 6}" text-anchor="middle">${escapeHtml(point.key.slice(0, 7))}</text>`;
  }).join('');

  const hover = points
    .filter((_, index) => index % Math.max(1, Math.round(points.length / 40)) === 0)
    .map((point) => `<circle class="dot" cx="${point.x.toFixed(1)}" cy="${point.y.toFixed(1)}" r="6" fill="transparent"><title>${escapeHtml(`${point.key}: ${num(point.value)} commits`)}</title></circle>`)
    .join('');

  return `<div class="chart-scroll">${svgBox(width, height, `
    <defs>
      <linearGradient id="area" x1="0" y1="0" x2="0" y2="1">
        <stop offset="0%" stop-color="#7c5cff" stop-opacity="0.55"/>
        <stop offset="100%" stop-color="#22d3ee" stop-opacity="0.02"/>
      </linearGradient>
      <linearGradient id="stroke" x1="0" y1="0" x2="1" y2="0">
        <stop offset="0%" stop-color="#7c5cff"/><stop offset="100%" stop-color="#22d3ee"/>
      </linearGradient>
    </defs>
    ${gridLines}
    <path d="${area}" fill="url(#area)"/>
    <path d="${line}" fill="none" stroke="url(#stroke)" stroke-width="2.5" stroke-linejoin="round" stroke-linecap="round"/>
    ${hover}${xTicks}
  `)}</div>`;
}

