/**
 * GitHub-style contribution calendar for the last year.
 * @param {Array<{ day: string, count: number }>} daily
 * @param {string} lastDay
 */
function calendarSvg(daily, lastDay) {
  const counts = new Map(daily.map((entry) => [entry.day, entry.count]));
  const endWeek = weekStart(lastDay);
  const startWeek = addDays(endWeek, -52 * 7);
  const weeks = 53;
  const cell = 13;
  const gap = 3;
  const padLeft = 34;
  const padTop = 20;
  const width = padLeft + weeks * (cell + gap) + 8;
  const height = padTop + 7 * (cell + gap) + 26;
  const max = Math.max(1, ...counts.values());
  const levels = (value) => {
    if (!value) return 0;
    const ratio = value / max;
    if (ratio <= 0.25) return 1;
    if (ratio <= 0.5) return 2;
    if (ratio <= 0.75) return 3;
    return 4;
  };

  let rects = '';
  const monthTicks = [];
  let lastMonth = null;

  for (let w = 0; w < weeks; w += 1) {
    for (let d = 0; d < 7; d += 1) {
      const day = addDays(startWeek, w * 7 + d);
      if (daysBetween(day, lastDay) < 0) continue;
      const value = counts.get(day) ?? 0;
      const x = padLeft + w * (cell + gap);
      const y = padTop + d * (cell + gap);
      rects += `<rect class="cell level-${levels(value)}" x="${x}" y="${y}" width="${cell}" height="${cell}" rx="3"><title>${escapeHtml(`${prettyDate(day)} — ${value} commits`)}</title></rect>`;
      const month = day.slice(0, 7);
      if (month !== lastMonth) {
        lastMonth = month;
        monthTicks.push(`<text x="${x}" y="${padTop - 6}" text-anchor="start">${escapeHtml(prettyMonth(month).slice(0, 3))}</text>`);
      }
    }
  }

  const dayLabels = [1, 3, 5]
    .map((day) => `<text x="${padLeft - 8}" y="${padTop + day * (cell + gap) + cell - 2}" text-anchor="end">${WEEKDAY_SHORT[day]}</text>`)
    .join('');

  const legend = [0, 1, 2, 3, 4]
    .map((level) => `<rect class="cell level-${level}" x="0" y="0" width="11" height="11" rx="2" transform="translate(${level * 15},0)"/>`)
    .join('');

  return `<div class="chart-scroll">${svgBox(width, height, `${rects}${monthTicks.join('')}${dayLabels}
    <g transform="translate(${width - 96},${height - 14})">
      <text x="-30" y="9" text-anchor="end">less</text>
      ${legend}
      <text x="82" y="9" text-anchor="start">more</text>
    </g>
  `)}</div>`;
}

