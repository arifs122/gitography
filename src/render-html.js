/**
 * HTML renderer — the showcase artefact.
 *
 * The output is a single, self-contained file: no external stylesheets, fonts,
 * scripts, images or CDN links. Charts are hand-built SVG, so the report looks
 * identical offline and works when opened straight from disk or attached to an
 * issue.
 *
 * All interpolated values pass through `escapeHtml()`.
 */

import {
  addDays,
  bytes,
  colorFor,
  compact,
  daysBetween,
  escapeHtml,
  initials,
  num,
  percent,
  prettyDate,
  prettyMonth,
  truncate,
  weekStart,
} from './util.js';

const BACKGROUNDS = ['#7c5cff', '#22d3ee', '#f472b6', '#fbbf24', '#34d399', '#60a5fa', '#a78bfa', '#fb7185', '#2dd4bf', '#f59e0b'];

/**
 * @param {object} report output of `analyze()`
 * @param {{ title?: string, subtitle?: string, theme?: 'dark'|'light', command?: string, generatedAt?: string }} [options]
 * @returns {string} complete HTML document
 */
export function renderHtml(report, options = {}) {
  const theme = options.theme === 'light' ? 'light' : 'dark';
  const repo = report.repository;
  const totals = report.totals;
  const title = options.title || (repo.owner ? `${repo.owner}/${repo.name}` : repo.name);
  const generatedAt = options.generatedAt || new Date().toISOString();
  const empty = totals.commits === 0;

  const body = [
    renderHero(report, { title, subtitle: options.subtitle }),
    empty
      ? renderEmptyState(report)
      : [
        renderSection('rhythm', 'Commit rhythm', 'When this project actually gets worked on.', rhythmGrid(report)),
        renderSection('growth', 'Momentum', 'How the codebase grew over its lifetime.', growthGrid(report)),
        renderSection('people', 'People', 'Who built it, and how.', peopleGrid(report)),
        renderSection('code', 'What it is made of', 'Languages, churn and the files that keep changing.', codeGrid(report)),
        renderSection('messages', 'How the team writes', 'Commit message hygiene, at a glance.', messagesGrid(report)),
        report.awards.length ? renderSection('awards', 'The awards wall', 'Trophies nobody asked for, everyone wants.', awardsGrid(report)) : '',
        renderNotes(report),
      ].join('\n'),
    renderFooter(report, { generatedAt, command: options.command }),
  ].join('\n');

  return `<!doctype html>
<html lang="en" data-theme="${theme}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="generator" content="gitography">
<meta name="description" content="Git history report for ${escapeHtml(title)} generated by gitography.">
<title>${escapeHtml(title)} · gitography</title>
<link rel="icon" href="data:image/svg+xml,${favicon()}">
<style>${STYLES}</style>
</head>
<body>
<div class="glow glow-a" aria-hidden="true"></div>
<div class="glow glow-b" aria-hidden="true"></div>
<div class="glow glow-c" aria-hidden="true"></div>
<button id="theme-toggle" class="theme-toggle" type="button" aria-label="Toggle colour theme">
  <span class="theme-icon theme-icon-dark">◐</span>
</button>
<a class="skip-link" href="#main">Skip to content</a>
${body}
<script>${CLIENT_SCRIPT}</script>
</body>
</html>
`;
}

