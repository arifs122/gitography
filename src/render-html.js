/**
 * @param {object} report
 */
function rhythmGrid(report) {
  const activity = report.activity;
  const streaks = activity.streaks;

  const cards = [];
  cards.push(`<article class="card card-wide">
    <h3>Punchcard</h3>
    <p class="card-sub">Commits by weekday and hour, in each author's local time.</p>
    ${punchcardSvg(activity.punchcard)}
  </article>`);

  cards.push(`<article class="card card-wide">
    <h3>Last 53 weeks</h3>
    <p class="card-sub">Every day of the past year — darker means more commits.</p>
    ${calendarSvg(activity.daily, report.range.lastDay)}
  </article>`);

  const peakDay = WEEKDAY_NAMES[activity.peakWeekday] ?? '—';
  const peakHour = `${String(activity.peakHour).padStart(2, '0')}:00`;

  cards.push(`<article class="card">
    <h3>Weekly rhythm</h3>
    <p class="card-sub">When the keyboards are warm.</p>
    <ul class="kv">
      <li><span>Busiest weekday</span><strong>${escapeHtml(peakDay)}</strong></li>
      <li><span>Busiest hour</span><strong>${escapeHtml(peakHour)}</strong></li>
      <li><span>Weekend share</span><strong>${percentReport(activity.byWeekday[0] + activity.byWeekday[6], report.totals.commits)}</strong></li>
      <li><span>Commits after midnight</span><strong>${percentReport(activity.byHour.slice(0, 5).reduce((a, b) => a + b, 0), report.totals.commits)}</strong></li>
    </ul>
  </article>`);

  cards.push(`<article class="card">
    <h3>Streaks &amp; breaks</h3>
    <p class="card-sub">Consistency, in numbers.</p>
    <ul class="kv">
      <li><span>Longest streak</span><strong>${num(streaks.longest.length)} days</strong></li>
      <li><span>Started</span><strong>${streaks.longest.start ? escapeHtml(prettyDate(streaks.longest.start)) : '—'}</strong></li>
      <li><span>Busiest day</span><strong>${activity.busiestDay ? `${num(activity.busiestDay.count)} <em>${escapeHtml(prettyDate(activity.busiestDay.date))}</em>` : '—'}</strong></li>
      <li><span>Longest silence</span><strong>${streaks.longestGap ? `${num(streaks.longestGap.days)} days` : '—'}</strong></li>
    </ul>
  </article>`);

  return `<div class="grid grid-2">${cards.join('\n')}</div>`;
}

function percentReport(part, whole) {
  return `${percent(part, whole).toFixed(1)}%`;
}

/* -------------------------------------------------------------- growth block */

/**
 * @param {object} report
 */
function growthGrid(report) {
  const activity = report.activity;
  const cumulative = activity.cumulative;
  const monthly = activity.monthly;

  const cards = [];
  if (cumulative.length > 1) {
    cards.push(`<article class="card card-wide">
      <h3>Cumulative commits</h3>
      <p class="card-sub">Total commits over time.</p>
      ${areaChartSvg(cumulative.map((c) => c.commits), cumulative.map((c) => c.week), { height: 220 })}
    </article>`);
  }

  if (monthly.length > 1) {
    cards.push(`<article class="card card-wide">
      <h3>Commits per month</h3>
      <p class="card-sub">The heartbeat of the project — peaks are releases, dips are… life.</p>
      ${columnChartSvg(monthly.map((m) => m.commits), monthly.map((m) => m.month), { height: 200 })}
    </article>`);
  }

  if (activity.yearly.length) {
    const maxYear = Math.max(...activity.yearly.map((y) => y.insertions + y.deletions), 1);
    cards.push(`<article class="card">
      <h3>Churn by year</h3>
      <p class="card-sub">Lines added vs. removed.</p>
      <ul class="churn-list">
        ${activity.yearly.map((year) => `<li>
          <span class="churn-year">${escapeHtml(year.year)}</span>
          <span class="churn-bars">
            <i class="churn-add" style="width:${percent(year.insertions, maxYear).toFixed(2)}%"></i>
            <i class="churn-del" style="width:${percent(year.deletions, maxYear).toFixed(2)}%"></i>
          </span>
          <span class="churn-num">${num(year.commits)} commits</span>
        </li>`).join('\n')}
      </ul>
      <p class="legend"><span class="swatch add"></span>added <span class="swatch del"></span>removed</p>
    </article>`);
  }

  cards.push(`<article class="card">
    <h3>Recent velocity</h3>
    <p class="card-sub">Commits in the trailing windows.</p>
    <ul class="kv">
      <li><span>Last 7 days</span><strong>${num(report.velocity.last7)}</strong></li>
      <li><span>Last 30 days</span><strong>${num(report.velocity.last30)}</strong></li>
      <li><span>Last 90 days</span><strong>${num(report.velocity.last90)}</strong></li>
      <li><span>Last 365 days</span><strong>${num(report.velocity.last365)}</strong></li>
    </ul>
  </article>`);

  return `<div class="grid grid-2">${cards.join('\n')}</div>`;
}

/* -------------------------------------------------------------- people block */

/**
 * @param {object} report
 */
function peopleGrid(report) {
  const contributors = report.contributors ?? [];
  const max = contributors.length ? contributors[0].commits : 1;

  const rows = contributors.map((person, index) => {
    const years = person.byYear ?? [];
    const maxYear = years.length ? Math.max(...years.map((y) => y.count)) : 1;
    const spark = years
      .map((y) => `<i style="height:${Math.max(8, percent(y.count, maxYear)).toFixed(0)}%" title="${escapeHtml(`${y.year}: ${y.count} commits`)}"></i>`)
      .join('');
    const badges = [
      person.nightShare >= 20 ? `<span class="pill violet">night owl ${person.nightShare.toFixed(0)}%</span>` : '',
      person.weekendShare >= 20 ? `<span class="pill cyan">weekend ${person.weekendShare.toFixed(0)}%</span>` : '',
      person.fixes >= 10 ? `<span class="pill green">${num(person.fixes)} fixes</span>` : '',
      person.filesTouched >= 50 ? `<span class="pill pink">${num(person.filesTouched)} files</span>` : '',
    ].filter(Boolean).join('');

    return `<li class="person">
      <span class="rank">${index + 1}</span>
      <span class="avatar" style="--avatar:${escapeHtml(colorFor(person.email || person.name))}">${escapeHtml(initials(person.name))}</span>
      <span class="person-body">
        <span class="person-top"><strong>${escapeHtml(person.name)}</strong> ${badges}</span>
        <span class="track"><i style="width:${percent(person.commits, max).toFixed(2)}%"></i></span>
        <span class="person-meta">
          ${num(person.commits)} commits <span class="dot">·</span> ${person.share.toFixed(1)}% <span class="dot">·</span>
          +${compact(person.insertions)} / −${compact(person.deletions)} <span class="dot">·</span>
          ${num(person.activeDays)} active days <span class="dot">·</span>
          ${escapeHtml(prettyDate(person.firstDate.slice(0, 10)))} → ${escapeHtml(prettyDate(person.lastDate.slice(0, 10)))}
        </span>
        <span class="spark" aria-hidden="true">${spark}</span>
      </span>
    </li>`;
  }).join('\n');

  const busFactor = report.busFactor;
  const riskLabel = { high: 'Critical', medium: 'Worth watching', low: 'Healthy' }[busFactor.risk] ?? 'Healthy';

  return `<div class="grid grid-people">
    <article class="card">
      <h3>Leaderboard</h3>
      <p class="card-sub">Top ${contributors.length} of ${num(report.contributorCount)} contributors — ${report.contributorShare.toFixed(0)}% of all commits.</p>
      <ol class="people">${rows || '<li class="person">No contributors found.</li>'}</ol>
    </article>
    <article class="card">
      <h3>Bus factor</h3>
      <p class="card-sub">How concentrated is the knowledge?</p>
      <p class="big-number">${num(busFactor.n)}</p>
      <p class="big-sub">${busFactor.n === 1 ? 'person' : 'people'} wrote ${busFactor.share.toFixed(0)}% of the history</p>
      <span class="pill ${busFactor.risk === 'high' ? 'red' : busFactor.risk === 'medium' ? 'amber' : 'green'}">${escapeHtml(riskLabel)} risk</span>
      <ul class="kv small">
        ${(busFactor.people ?? []).map((p) => `<li><span>${escapeHtml(truncate(p.name, 24))}</span><strong>${p.share.toFixed(0)}%</strong></li>`).join('\n')}
      </ul>
      <h4 class="sub-head">Most cross-cutting files</h4>
      <ul class="mini-list">
        ${(report.riskiest ?? []).map((file) => `<li><code>${escapeHtml(truncate(file.path, 38))}</code><span>${num(file.commits)} commits · ${file.authors} authors</span></li>`).join('\n')}
      </ul>
    </article>
  </div>`;
}

/* ---------------------------------------------------------------- code block */

/**
 * @param {object} report
 */
function codeGrid(report) {
  const languages = report.languages ?? [];
  const hotspots = report.hotspots ?? [];
  const maxLang = languages.length ? languages[0].bytes : 1;
  const maxHotspot = hotspots.length ? hotspots[0].churn : 1;

  const donut = languages.length
    ? donutSvg(languages.map((language, index) => ({
      label: language.name,
      value: language.bytes,
      color: BACKGROUNDS[index % BACKGROUNDS.length],
    })), { size: 200 })
    : '';

  return `<div class="grid grid-2">
    <article class="card">
      <h3>Languages</h3>
      <p class="card-sub">By tracked bytes at HEAD — ${report.codeShare.toFixed(0)}% of it is code. Charts and metadata excluded.</p>
      <div class="donut-row">
        ${donut}
        <ul class="legend-list">
          ${languages.map((language, index) => `<li>
            <span class="swatch" style="background:${BACKGROUNDS[index % BACKGROUNDS.length]}"></span>
            <span class="legend-name">${escapeHtml(language.name)}</span>
            <span class="legend-bar"><i style="width:${percent(language.bytes, maxLang).toFixed(2)}%"></i></span>
            <span class="legend-value">${language.share.toFixed(1)}%</span>
          </li>`).join('\n')}
        </ul>
      </div>
    </article>

    <article class="card">
      <h3>Hotspots</h3>
      <p class="card-sub">Files with the most churn — the ones that deserve tests and documentation.</p>
      <ul class="hotspots">
        ${hotspots.slice(0, 12).map((hotspot) => `<li>
          <code>${escapeHtml(truncate(hotspot.path, 44))}</code>
          <span class="heat"><i style="width:${hotspot.heat.toFixed(2)}%"></i></span>
          <span class="heat-num">${num(hotspot.commits)} commits · +${compact(hotspot.insertions)} / −${compact(hotspot.deletions)}</span>
        </li>`).join('\n')}
      </ul>
    </article>
  </div>`;
}

