/**
 * @param {object} report
 * @param {{ title: string, subtitle?: string }} meta
 */
function renderHero(report, meta) {
  const totals = report.totals;
  const repo = report.repository;

  const tiles = [
    { label: 'Commits', value: totals.commits, hint: `${num(totals.mergeCommits)} merge commits` },
    { label: 'Contributors', value: totals.contributors, hint: `${num(totals.filesTracked)} files tracked` },
    { label: 'Lines added', value: totals.insertions, hint: `avg +${Math.round(totals.avgLinesPerCommit / 2)} per commit`, tone: 'green' },
    { label: 'Lines removed', value: totals.deletions, hint: `avg −${Math.round(totals.avgLinesPerCommit / 2)} per commit`, tone: 'red' },
    { label: 'Active days', value: totals.activeDays, hint: `${totals.activityRate.toFixed(1)}% of the period` },
    { label: 'Commits / week', value: report.velocity.perWeek, decimals: 1, hint: `${report.velocity.perMonth.toFixed(1)} per month` },
  ];

  const metaBits = [
    repo.branch ? `on ${repo.branch}` : null,
    repo.head ? `at ${repo.head}` : null,
    repo.tags?.latest ? `latest tag ${repo.tags.latest}` : null,
    repo.branchCount ? `${num(repo.branchCount)} branches` : null,
    repo.webUrl ? `<a href="${escapeHtml(repo.webUrl)}" rel="noopener">${escapeHtml(repo.webUrl.replace(/^https?:\/\//, ''))}</a>` : null,
  ].filter(Boolean);

  return `<header class="hero" id="top">
  <div class="wrap">
    <p class="eyebrow">gitography<span class="dot">·</span>repository report</p>
    <h1>${escapeHtml(meta.title)}</h1>
    ${meta.subtitle ? `<p class="lede">${escapeHtml(meta.subtitle)}</p>` : ''}
    <p class="lede range">
      ${escapeHtml(prettyDate(report.range.firstDay))} <span class="arrow">→</span> ${escapeHtml(prettyDate(report.range.lastDay))}
      <span class="dot">·</span> ${escapeHtml(report.range.age)} of history
    </p>
    <ul class="meta">${metaBits.map((bit) => `<li>${bit}</li>`).join('')}</ul>

    <div class="tiles">
      ${tiles.map((tile) => `<div class="tile">
        <span class="tile-label">${escapeHtml(tile.label)}</span>
        <strong class="tile-value ${tile.tone ?? ''}" data-count="${Number(tile.value) || 0}" data-decimals="${tile.decimals ?? 0}">0</strong>
        <span class="tile-hint">${escapeHtml(tile.hint)}</span>
      </div>`).join('\n')}
    </div>
  </div>
</header>`;
}

/**
 * @param {string} id
 * @param {string} title
 * @param {string} subtitle
 * @param {string} content
 */
function renderSection(id, title, subtitle, content) {
  return `<section class="section wrap" id="${id}">
  <div class="section-head">
    <h2>${escapeHtml(title)}</h2>
    <p>${escapeHtml(subtitle)}</p>
  </div>
  ${content}
</section>`;
}

