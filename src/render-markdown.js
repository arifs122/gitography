/**
 * Markdown renderer — designed to be pasted straight into a README.
 */

import { compact, num, prettyDate, truncate } from './util.js';

/**
 * @param {object} report output of `analyze()`
 * @param {{ embed?: boolean }} [options]
 * @returns {string}
 */
export function renderMarkdown(report, options = {}) {
  const { embed = false } = options;
  const repo = report.repository;
  const totals = report.totals;
  const title = repo.owner ? `${repo.owner}/${repo.name}` : repo.name;
  const lines = [];

  if (!embed) {
    lines.push(`# ${title} — repository report`, '');
    lines.push(`> Generated by [gitography](https://github.com/arifs122/gitography) on ${prettyDate(report.range.asOf.slice(0, 10))}.`, '');
  } else {
    lines.push(`## Repository report`, '');
  }

  if (totals.commits === 0) {
    lines.push('_No commits found in this repository yet._', '');
    return lines.join('\n');
  }

  // ----------------------------------------------------------------- headline
  lines.push('| Metric | Value |', '| --- | --- |');
  lines.push(`| Commits | ${num(totals.commits)} |`);
  lines.push(`| Contributors | ${num(totals.contributors)} |`);
  lines.push(`| Files tracked | ${num(totals.filesTracked)} |`);
  lines.push(`| Lines added | +${num(totals.insertions)} |`);
  lines.push(`| Lines removed | −${num(totals.deletions)} |`);
  lines.push(`| History | ${report.range.age} (${prettyDate(report.range.firstDay)} → ${prettyDate(report.range.lastDay)}) |`);
  lines.push(`| Active days | ${num(totals.activeDays)} (${totals.activityRate.toFixed(1)}% of the period) |`);
  lines.push(`| Commits / week | ${report.velocity.perWeek.toFixed(1)} |`);
  lines.push(`| Bus factor | ${report.busFactor.n} (${report.busFactor.share.toFixed(0)}% of commits) |`);
  lines.push('');

  // ------------------------------------------------------------- contributors
  if (report.contributors.length) {
    lines.push('### Top contributors', '');
    lines.push('| # | Contributor | Commits | Share | Lines (+/−) |');
    lines.push('| ---: | --- | ---: | ---: | ---: |');
    for (const [index, person] of report.contributors.slice(0, 10).entries()) {
      lines.push(
        `| ${index + 1} | ${escapePipe(person.name)} | ${num(person.commits)} | ${person.share.toFixed(1)}% `
        + `| +${compact(person.insertions)} / −${compact(person.deletions)} |`,
      );
    }
    lines.push('');
  }

  // ---------------------------------------------------------------- languages
  if (report.languages.length) {
    lines.push('### Languages', '');
    lines.push('| Language | Share | Size | Files |', '| --- | ---: | ---: | ---: |');
    for (const language of report.languages.slice(0, 10)) {
      lines.push(`| ${escapePipe(language.name)} | ${language.share.toFixed(1)}% | ${formatBytes(language.bytes)} | ${num(language.files)} |`);
    }
    lines.push('');
  }

  // ----------------------------------------------------------------- hotspots
  if (report.hotspots.length) {
    lines.push('### Hotspots', '');
    lines.push(`Files that change the most — the ones worth refactoring, testing and documenting.`, '');
    lines.push('| File | Commits | Churn | Authors |', '| --- | ---: | ---: | ---: |');
    for (const hotspot of report.hotspots.slice(0, 10)) {
      lines.push(`| \`${escapePipe(truncate(hotspot.path, 60))}\` | ${num(hotspot.commits)} | ${num(hotspot.churn)} | ${hotspot.authors} |`);
    }
    lines.push('');
  }

  // ------------------------------------------------------------------- awards
  if (report.awards.length) {
    lines.push('### Awards', '');
    for (const award of report.awards) {
      lines.push(`- **${award.emoji} ${award.title} — ${escapePipe(award.headline)}**: ${escapePipe(award.detail)}`);
    }
    lines.push('');
  }

  // ------------------------------------------------------------------- weekly
  const weekly = report.activity.weekly;
  if (weekly.length > 1) {
    lines.push('### Commits per week', '');
    lines.push('```');
    lines.push(asciiSparkline(weekly.map((w) => w.commits), 64));
    lines.push(`first: ${prettyDate(weekly[0].week)}    last: ${prettyDate(weekly[weekly.length - 1].week)}`);
    lines.push('```', '');
  }

  return lines.join('\n');
}

/**
 * @param {number[]} values
 * @param {number} width
 */
function asciiSparkline(values, width) {
  const blocks = ' ▁▂▃▄▅▆▇█';
  const step = Math.max(1, Math.ceil(values.length / width));
  const sampled = [];
  for (let i = 0; i < values.length; i += step) {
    sampled.push(Math.max(...values.slice(i, i + step)));
  }
  const max = Math.max(...sampled, 1);
  return sampled.map((v) => blocks[Math.min(blocks.length - 1, Math.round((v / max) * (blocks.length - 1)))]).join('');
}

/**
 * @param {number} bytes
 */
function formatBytes(bytes) {
  const units = ['B', 'KB', 'MB', 'GB'];
  let value = Number(bytes) || 0;
  let index = 0;
  while (value >= 1024 && index < units.length - 1) {
    value /= 1024;
    index += 1;
  }
  return `${index === 0 ? Math.round(value) : value.toFixed(1)} ${units[index]}`;
}

/**
 * @param {string} value
 */
function escapePipe(value) {
  return String(value).replace(/\|/g, '\\|').replace(/\n/g, ' ');
}
